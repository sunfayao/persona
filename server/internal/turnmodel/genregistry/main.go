// Command genregistry exports the node's canonical tool registry for the browser.
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"

	"github.com/sunfayao/persona/server/internal/turnmodel"
)

func main() {
	out := flag.String("out", "", "generated registry file")
	check := flag.Bool("check", false, "verify the generated file without writing it")
	flag.Parse()
	if err := export(*out, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func export(out string, check bool) error {
	kinds := turnmodel.CanonicalRegistry()
	header := "// Code generated by the Go turn model registry. DO NOT EDIT.\n"
	value := "export const CANONICAL_TOOL_KINDS: Readonly<Record<string, ToolKind>> = "
	table, err := json.MarshalIndent(kinds, "", "  ")
	if filepath.Ext(out) == ".js" {
		table, err = json.Marshal(kinds)
		value = "export const CanonicalToolKinds = Object.freeze("
	} else {
		header += "import type { ToolKind } from \"./turn-model-wire\";\n\n"
	}
	if err != nil {
		return err
	}
	if filepath.Ext(out) == ".js" {
		table = append(table, ')')
	}
	result := []byte(header + value + string(table) + ";\n")
	if !check {
		return os.WriteFile(out, result, 0o644)
	}
	old, err := os.ReadFile(out)
	if err != nil {
		return err
	}
	if !bytes.Equal(old, result) {
		return fmt.Errorf("%s is out of date; run go generate ./internal/turnmodel from server", out)
	}
	return nil
}
