def gofmt(src: str) -> str:
    exe = shutil.which("gofmt")
    if not exe:
        raise SchemaError("gofmt is not on PATH: the Go output is gofmt's")
    r = subprocess.run([exe], input=src, capture_output=True, text=True)
    if r.returncode != 0:
        raise SchemaError("gofmt: " + r.stderr.strip())
    return r.stdout


def for_apps(defs: dict[str, Def]) -> dict[str, Def]:
    """The definitions the apps read: none of a plugin-side file's, which the apps' own may not refer to."""
    apps = {n: d for n, d in defs.items() if not d.side}

    def refs(t: TypeRef):
        while t is not None:
            if t.kind == "ref":
                yield t.ref
            t = t.of

    for d in apps.values():
        used = [r for t in [*(f.type for f in d.fields), *d.json_types] for r in refs(t)] + d.variants
        for r in used:
            if defs[r].side:
                raise SchemaError(f"{d.name} refers to {r}, which is {defs[r].side}-side: the apps do not have it")
    return apps


def outputs(defs: dict[str, Def]) -> dict[Path, str]:
    apps = for_apps(defs)
    # The calls are what a program and the hub say to each other: the SDKs' only.
    calls = load_calls(defs)
    ts, ts_apps = gen_ts(defs, calls), gen_ts(apps)
    out = {GO_OUT: gofmt(gen_go(defs, calls))}
    for p in TS_OUTS:
        out[p] = ts if p == TS_SDK_OUT else ts_apps
    for f in SCHEMA_FILES:
        out[GO_SCHEMA_DIR / f] = (SCHEMA_DIR / f).read_text()
    out.update(wire_outputs())
    return {p: (s.rstrip("\n") + "\n") for p, s in out.items()}


WIRE_TARGETS = ("ts", "go", "js")


def gen_js(defs: dict[str, Def], header: str) -> str:
    """Runtime SDK vocabulary only: one frozen array per enum."""
    return "\n".join([header, *(
        f"export const {plural(d.name)}=Object.freeze({json.dumps(d.values, separators=(',', ':'))});"
        for d in defs.values() if d.kind == "enum"
    )])


def declared_package(out: Path, suffix: str, derived: str) -> str:
    """The package of a generated file: derived from its directory, and the one every hand-written file there names."""
    pattern = re.compile(r"^package\s+([\w.]+)", re.M)
    for other in sorted(out.parent.glob("*" + suffix)):
        if other == out or other.name.endswith("_test.go"):
            continue
        m = pattern.search(other.read_text())
        if m and m.group(1) != derived:
            raise SchemaError(f"{out.parent.name}/{out.name}: {other.name} is package {m.group(1)}, not {derived}")
    return derived


def wire_outputs() -> dict[Path, str]:
    """The hub wire types: each schema/wire/<domain>.schema.json into the files its x-out names (ts, go). Go takes
    the package of the directory it is written to."""
    out: dict[Path, str] = {}
    for path in sorted(WIRE_DIR.glob("*.schema.json")):
        doc = json.loads(path.read_text())
        targets = doc.get("x-out", {})
        if not set(targets) <= set(WIRE_TARGETS) or not targets:
            raise SchemaError(f"{path.name}: x-out names output files for {', '.join(WIRE_TARGETS)} only")
        defs = load(WIRE_DIR, [path.name])
        about = f"{doc.get('title', path.name)}: {doc.get('description', '')}".rstrip()
        header = [f"// Generated by scripts/gen/extension_schema.py from schema/wire/{path.name}; do not edit.",
                  f"// {about}"]
        if "ts" in targets:
            out[ROOT / targets["ts"]] = gen_ts(defs, header=header)
        if "go" in targets:
            # The package's own files are hand-written: no package doc here, and a registry of its own per schema.
            go = ROOT / targets["go"]
            package = declared_package(go, ".go", go.parent.name)
            stem = path.name.removesuffix(".schema.json")
            out[go] = gofmt(gen_go(defs, header=[f"// Code generated by scripts/gen/extension_schema.py from "
                                                 f"schema/wire/{path.name}. DO NOT EDIT.", f"// {about}"],
                                   package=package, package_doc="", registry=lower_camel(stem) + "Defs"))
        if "js" in targets:
            out[ROOT / targets["js"]] = gen_js(defs, header[0])
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="compare instead of writing; exit 1 on a difference")
    args = ap.parse_args()
    try:
        files = outputs(load())
    except SchemaError as e:
        print(f"schema: {e}", file=sys.stderr)
        return 2
    stale = []
    for path, text in files.items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(path.relative_to(ROOT))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            if not path.exists() or path.read_text() != text:
                path.write_text(text)
                print(f"wrote {path.relative_to(ROOT)}")
    if not args.check:
        # sdk/ts/src/wire.ts is also in the bundle `personad extension new` writes extensions from.
        subprocess.run([sys.executable, str(ROOT / "scripts" / "gen" / "sdk_bundle.py")], check=True)
    if stale:
        print("generated files differ from their schemas (run python3 scripts/gen/extension_schema.py):", file=sys.stderr)
        for p in stale:
            print(f"  {p}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
